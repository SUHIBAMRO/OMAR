def find_para_exact(paras, text):
    hits = [p for p in paras if p.text.strip() == text]
    assert len(hits) == 1, f'{len(hits)} paragraphs exactly match {text!r}'
    return hits[0]


def replace_paragraph_text(para, new_text):
    for r in list(para.runs):
        r._r.getparent().remove(r._r)
    para.add_run(new_text)


def insert_table_after(doc, anchor_para, header, rows, col_widths_in=None):
    tbl = doc.add_table(rows=1 + len(rows), cols=len(header))
    tbl.style = doc.tables[0].style
    for j, h in enumerate(header):
        tbl.rows[0].cells[j].text = h
    for i, row in enumerate(rows, start=1):
        for j, v in enumerate(row):
            tbl.rows[i].cells[j].text = v
    tbl_elem = tbl._tbl
    tbl_elem.getparent().remove(tbl_elem)
    anchor_para._p.addnext(tbl_elem)
    return tbl


def insert_paragraph_after(doc, anchor_para, text):
    p = doc.add_paragraph()
    p.add_run(text)
    p_elem = p._p
    p_elem.getparent().remove(p_elem)
    anchor_para._p.addnext(p_elem)
    return Paragraph(p_elem, anchor_para._parent)


def insert_figure_after(doc, anchor_para, image_path, caption_text, width_in):
    img_p = doc.add_paragraph()
    img_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    img_p.add_run().add_picture(image_path, width=Inches(width_in))
    img_elem = img_p._p
    img_elem.getparent().remove(img_elem)

    cap_p = doc.add_paragraph()
    cap_run = cap_p.add_run(caption_text)
    cap_run.italic = True
    cap_run.font.size = Pt(9)
    cap_elem = cap_p._p
    cap_elem.getparent().remove(cap_elem)

    anchor_para._p.addnext(cap_elem)
    anchor_para._p.addnext(img_elem)
    return Paragraph(cap_elem, anchor_para._parent)


def replace_figure_in_place(doc, caption_text, new_image_path, width_in):
    """Removes the image immediately preceding `caption_text`'s paragraph
    and the caption paragraph itself, then re-inserts a fresh image with
    the SAME caption text at the same document position (established
    pattern, see add_b2_neohookean_multires_result_to_report.py)."""
    paras = list(doc.paragraphs)
    fig_caption = find_para_exact(paras, caption_text)
    old_img_p = fig_caption._p.getprevious()
    assert old_img_p is not None and old_img_p.findall('.//' + qn('w:drawing')), \
        f'expected an image paragraph immediately before caption {caption_text!r}'
    prior_anchor = old_img_p.getprevious()
    assert prior_anchor is not None
    old_img_p.getparent().remove(old_img_p)
    fig_caption._p.getparent().remove(fig_caption._p)
    anchor = Paragraph(prior_anchor, fig_caption._parent)
    insert_figure_after(doc, anchor, new_image_path, caption_text, width_in)


def update_breakeven_table(doc, header_row_target, operator_header_new=None):
    found = False
    for t in doc.tables:
        header = [c.text for c in t.rows[0].cells]
        if header != header_row_target:
            continue
        found = True
        if operator_header_new is not None:
            t.rows[0].cells[2].text = operator_header_new
        for row in t.rows[1:]:
            case = row.cells[0].text
            if case in BREAKEVEN_ROWS:
                for j, v in enumerate(BREAKEVEN_ROWS[case], start=1):
                    row.cells[j].text = v
        break
    assert found, f'break-even table with header {header_row_target} not found'


