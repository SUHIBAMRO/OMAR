"""Cluster job factory and result import (2026-11-24).

What was done by hand for jobs 3280560-3280562, as code. The agent never connects to the
cluster: it writes the job, the transfer bundle and the instructions; a person submits the
job and brings the results back; the import verifies them before anything is merged.

  make_job(...)   writes  <name>_job.sh            the LSF script (the bsub form that the
                                                   cluster accepted: memory in MB in rusage,
                                                   one GPU slot requested in BatchGPU)
                          transfer/<name>.tar.gz   the code at HEAD (GitHub is not reachable
                                                   from the cluster) + its md5
                          transfer/<name>.md       step-by-step instructions, one command per
                                                   step, with the expected outputs
  import_result(...)      verifies the md5 of a returned file (the person prints it on the
                          cluster), then merges a JSON result into the stored file: new keys
                          are added; an existing key must be identical, or the import stops

    python -m omar_pfem.verification_agent.job_factory make <name> "<python command>" \\
           --mem-mb 16000 --hours 12 --outputs a.json [b.json ...]
    python -m omar_pfem.verification_agent.job_factory import <returned.json> <md5> <stored.json>
"""
import argparse
import hashlib
import json
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
PE = os.path.abspath(os.path.join(HERE, "..", ".."))           # Practical_Examples
ROOT = os.path.abspath(os.path.join(PE, ".."))
BRANCH = "claude/claude-code-question-d307wp"
RAW = f"https://github.com/SUHIBAMRO/OMAR/raw/{BRANCH}/transfer"
LOGIN = "<login>@cslogin.tu-ilmenau.de"


def _md5(path):
    return hashlib.md5(open(path, "rb").read()).hexdigest()


def job_script(name, command, mem_mb, hours, outputs):
    return f"""#!/bin/bash
# {name}: generated by job_factory.py for MANUAL submission (no agent submits jobs).
#   bsub -gpu "num=1:mode=exclusive_process" -q BatchGPU -R "span[hosts=1] rusage[mem={mem_mb}]" \\
#        -n 8 -W {hours}:00 -o {name}.%J.out -e {name}.%J.err < {name}_job.sh
# Outputs to bring back: {', '.join(outputs)}
set -e
source ~/miniconda3/etc/profile.d/conda.sh
conda activate omar
cd ~/OMAR/Practical_Examples
python -u {command}
"""


def _print_command(outputs):
    from omar_pfem.verification_agent.cluster_ladder import print_command
    rel = [o.replace("omar_pfem/verification_agent/", "") for o in outputs]
    return print_command(rel)


def make_job(name, command, mem_mb, hours, outputs, include=("Practical_Examples/omar_pfem",),
             extra=()):
    """extra: files (absolute paths in the repository) added to the bundle although not yet
    committed, e.g. a job spec written just now."""
    script = os.path.join(PE, f"{name}_job.sh")
    open(script, "w").write(job_script(name, command, mem_mb, hours, outputs))
    os.makedirs(os.path.join(ROOT, "transfer"), exist_ok=True)
    tar = os.path.join(ROOT, "transfer", f"{name}.tar.gz")
    rel_script = os.path.relpath(script, ROOT)
    # the bundle is the committed tree plus the new job script (written just now)
    subprocess.run(["git", "archive", "--format=tar", "-o", tar + ".tar", "HEAD", *include],
                   cwd=ROOT, check=True)
    subprocess.run(["tar", "rf", tar + ".tar", rel_script], cwd=ROOT, check=True)
    for e in extra:
        subprocess.run(["tar", "rf", tar + ".tar", os.path.relpath(e, ROOT)], cwd=ROOT, check=True)
    subprocess.run(["gzip", "-9", "-n", "-f", tar + ".tar"], cwd=ROOT, check=True)
    os.replace(tar + ".tar.gz", tar)
    md5 = _md5(tar)
    steps = f"""# Job `{name}`: step by step

1. **On your computer**, download (opens in the browser, lands in Downloads):
   {RAW}/{name}.tar.gz
2. **On your computer**, in a new PowerShell window:
   ```
   scp -O $HOME\\Downloads\\{name}.tar.gz {LOGIN}:~/
   ```
3. **On the cluster** (after `ssh {LOGIN}`), one line at a time:
   ```
   md5sum ~/{name}.tar.gz
   ```
   It must print `{md5}`. Then:
   ```
   cd ~/OMAR && tar xzf ~/{name}.tar.gz && cd Practical_Examples
   bsub -gpu "num=1:mode=exclusive_process" -q BatchGPU -R "span[hosts=1] rusage[mem={mem_mb}]" -n 8 -W {hours}:00 -o {name}.%J.out -e {name}.%J.err < {name}_job.sh
   ```
   Expected: `Job <number> is submitted to queue <BatchGPU>.`
4. **When `bjobs` no longer lists it**, run this one line and paste everything it prints into
   the chat:
   ```
   {_print_command(outputs)}
   ```
   (Outputs: {', '.join(outputs)}. The chat side rebuilds each file, checks its md5 and imports it.)
"""
    md = os.path.join(ROOT, "transfer", f"{name}.md")
    open(md, "w").write(steps)
    return {"script": script, "bundle": tar, "md5": md5, "instructions": md}


def import_result(returned, md5, stored):
    got = _md5(returned)
    if got != md5:
        raise SystemExit(f"md5 mismatch: {got} != {md5} (the copy is not identical)")
    new = json.load(open(returned))
    if not os.path.exists(stored):
        json.dump(new, open(stored, "w"), indent=1)
        return {"added": list(new) if isinstance(new, dict) else len(new), "kept": []}
    old = json.load(open(stored))
    if not (isinstance(old, dict) and isinstance(new, dict)):
        raise SystemExit("merge is defined for JSON objects only; replace by hand")
    clash = [k for k in new if k in old and old[k] != new[k]]
    if clash:
        raise SystemExit(f"stored values differ for {clash}: not merged")
    added = [k for k in new if k not in old]
    old.update({k: new[k] for k in added})
    json.dump(old, open(stored, "w"), indent=1)
    return {"added": added, "kept": [k for k in new if k not in added]}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("make")
    m.add_argument("name")
    m.add_argument("command")
    m.add_argument("--mem-mb", type=int, required=True)
    m.add_argument("--hours", type=int, required=True)
    m.add_argument("--outputs", nargs="+", required=True)
    i = sub.add_parser("import")
    i.add_argument("returned")
    i.add_argument("md5")
    i.add_argument("stored")
    a = ap.parse_args()
    if a.cmd == "make":
        print(json.dumps(make_job(a.name, a.command, a.mem_mb, a.hours, a.outputs), indent=1))
    else:
        print(json.dumps(import_result(a.returned, a.md5, a.stored), indent=1))
